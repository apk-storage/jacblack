using System.Collections.Generic;

namespace JacBlack.Models.Api
{
    public class TorrentInfo
    {
        public int quality { get; set; }

        public string videotype { get; set; }

        public HashSet<string> voices { get; set; }

        public HashSet<int> seasons { get; set; }

        public string[] types { get; set; }

        public string sizeName { get; set; }

        public string name { get; set; }

        public string originalname { get; set; }

        public int relased { get; set; }

        /// <summary>
        /// Код IMDB раздачи, если он известен. Проставлен примерно у 40% базы —
        /// его сообщают англоязычные источники, а остальным он раздан через
        /// словарь по паре «оригинальное название + год».
        ///
        /// Нужен выдаче, а не только базе: по нему поиск из карточки отличает
        /// одноимённые вещи, чего строкой не сделать — у аниме «Мужчина средних
        /// лет из глубинки…» оригинальное название тоже начинается с «From».
        /// </summary>
        public string imdb { get; set; }

        /// <summary>
        /// Код Кинопоиска. Нужен выдаче ровно затем же, зачем код IMDB, но
        /// закрывает другую половину случаев: IMDB разводит тёзок у зарубежных
        /// вещей, Кинопоиск — у русских, где кода IMDB нет ни у кого.
        /// </summary>
        public string kinopoisk { get; set; }

        /// <summary>
        /// Проверено ли число раздающих живым опросом прямо сейчас.
        ///
        /// Ложь означает, что показан снимок из базы — он может быть сделан
        /// хоть полгода назад, и именно это выглядело как враньё: у мёртвой
        /// раздачи стояло «5 сидов», у живой с двумя сотнями — тоже «5».
        ///
        /// Отдавать всё равно надо: без числа выбирать не из чего. Но человек
        /// должен видеть, что оно непроверено.
        ///
        /// Замечание о пределе: даже проверенное число — это состояние на
        /// момент последнего анонса пиров, а он бывает раз в полчаса.
        /// Секундной точности в этом протоколе не существует ни у кого.
        /// </summary>
        public bool seedersLive { get; set; }

        /// <summary>
        /// Трекер не сообщает число раздающих вовсе.
        ///
        /// Так у lostfilm: счётчиков на сайте нет, и в записи стоит единица,
        /// проставленная разбором вручную. То есть «1 раздающий» у него
        /// никогда не был данными — это заглушка, которая читалась как факт.
        ///
        /// Само число оставляем как есть: обнулить значит объявить живую
        /// раздачу мёртвой и утопить её в сортировке. Но выдача должна честно
        /// сказать, что числа нет, а не показывать выдуманное.
        /// </summary>
        public bool seedersUnknown { get; set; }

        /// <summary>
        /// Адреса страниц всех трекеров, чьи копии склеены в эту раздачу.
        ///
        /// При склейке остаётся только один адрес — первого источника, — и
        /// копия с другого трекера становится недостижимой. Из-за этого живой
        /// опрос не находил её: запись помечена как «rutor, kinozal», а адрес
        /// в ней рутора, и по нему идентификатор kinozal не вытащить. Замер
        /// 01.08.2026: 13 раздач из 77 оставались без проверки именно поэтому.
        /// </summary>
        public List<string> sources { get; set; }

        /// <summary>
        /// Сводка дорожек: кодек картинки, кодеки звука и — если у раздачи есть
        /// разбор ffprobe — сами дорожки с языком и числом каналов.
        ///
        /// Пустую сводку не отдаём вовсе: у большинства раздач ffprobe нет, и
        /// карточка не должна показывать пустые плашки.
        /// </summary>
        public JacBlack.Infrastructure.Parsing.MediaTracks.Summary media { get; set; }
    }
}
