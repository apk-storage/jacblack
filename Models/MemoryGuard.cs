namespace JacBlack.Models
{
    /// <summary>
    /// Присмотр за памятью: когда уплотнять кучу больших объектов.
    ///
    /// Зачем. Замер 13.09.2026: служба держала 2,9 ГБ при 598 МБ живых объектов.
    /// Разница почти вся в LOH — 794 МБ, из них 339 МБ дыр. Большие объекты
    /// (страницы трекеров, JSON, массивы под разбор) уходят туда постоянно, а
    /// LOH по умолчанию НЕ уплотняется: объект освободился, место осталось
    /// занятым для системы. Дважды это кончилось OutOfMemory и зависанием.
    ///
    /// Почему по признаку, а не по расписанию: уплотнение LOH — блокирующая
    /// сборка, на восьмистах мегабайтах она занимает секунды, а поиск у нас
    /// укладывается в 800 мс. Платить этим просто так нельзя, поэтому три
    /// условия сразу — дыр больше порога, доля дыр велика и с прошлого раза
    /// прошёл минимальный срок.
    /// </summary>
    public class MemoryGuard
    {
        /// <summary>Присматривать за памятью вообще.</summary>
        public bool enable { get; set; }

        /// <summary>Как часто смотреть на кучу.</summary>
        public int checkMinutes { get; set; }

        /// <summary>
        /// Сколько мегабайт дыр в LOH считать поводом. Ниже этого уплотнять
        /// незачем: выигрыш не окупит паузы.
        /// </summary>
        public int fragmentedMb { get; set; }

        /// <summary>
        /// И какую долю LOH эти дыры должны занимать, в процентах. Без доли
        /// порог в мегабайтах врал бы: 300 МБ дыр на 3 ГБ LOH — это норма
        /// работы, а на 800 МБ — уже половина впустую.
        /// </summary>
        public int fragmentedPercent { get; set; }

        /// <summary>Не чаще чем раз в столько минут, даже если признак держится.</summary>
        public int minIntervalMinutes { get; set; }

        /// <summary>
        /// Тихие часы по местному времени сервера, начало и конец. Уплотнение
        /// вне них не делается.
        ///
        /// Замер 13.09.2026: уплотнение LOH на 274 МБ заняло **14 секунд**
        /// полной остановки — за это время не отвечает ни поиск, ни health.
        /// Раз в час такое ронять на людей нельзя, а ночью, когда телевизоры
        /// выключены, эти секунды никому не стоят ничего. Если разбухнет
        /// быстрее, чем за сутки, сработает сторож памяти на awg — он
        /// перезапустит службу, и это дешевле блокировки в прайм-тайм.
        /// </summary>
        public int quietFromHour { get; set; }

        /// <summary>Конец тихих часов, не включая. 3 и 6 значит «с трёх до шести».</summary>
        public int quietToHour { get; set; }
    }
}
