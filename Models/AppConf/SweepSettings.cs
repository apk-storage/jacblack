namespace JacBlack.Models.AppConf
{
    /// <summary>
    /// Фоновая проверка живости раздач. Отдельно от поискового опроса:
    /// тот работает по выдаче и торопится, этот идёт по всей базе и никуда не спешит.
    /// </summary>
    public class SweepSettings
    {
        public bool enable { get; set; } = true;

        /// <summary>Сколько ключей базы разбирать за один прогон.</summary>
        public int batchKeys { get; set; } = 3000;

        /// <summary>Потолок по времени на прогон, секунд. Дошли до него — останавливаемся и запоминаем место.</summary>
        public int maxSeconds { get; set; } = 900;

        /// <summary>Пауза между обращениями к одному трекеру, мс. Не долбим чужие серверы.</summary>
        public int delayMs { get; set; } = 400;

        /// <summary>Таймаут одного обращения к трекеру, мс. Здесь можно щедрее, чем в поиске.</summary>
        public int trackerTimeoutMs { get; set; } = 3000;

        /// <summary>Хешей в одном пакете. Протокол допускает до 74.</summary>
        public int maxHashesPerRequest { get; set; } = 70;

        /// <summary>
        /// Сколько РАЗНЫХ трекеров опрашивать одновременно.
        ///
        /// Раньше обход шёл строго по одному, и каждый мёртвый анонс стоил
        /// целого таймаута. Итог 29.07.2026: прогон упирался в потолок 900 с,
        /// продвинувшись на 70 ключей из 3000 — то есть проверено было 19 тысяч
        /// раздач из 1.27 миллиона. Пауза `delayMs` осталась на месте: она
        /// про вежливость к ОДНОМУ трекеру, а разные друг другу не мешают.
        /// </summary>
        public int trackerConcurrency { get; set; } = 8;

        /// <summary>
        /// Сколько нулей подряд считать приговором. Достигшие порога попадают
        /// в отчёт, а удаляются только если включено удаление.
        /// </summary>
        public int deadThreshold { get; set; } = 5;

        /// <summary>
        /// Сколько нулей подряд нужно, чтобы УДАЛИТЬ запись. Порог отдельный
        /// и намеренно много больше того, по которому раздачу прячут.
        ///
        /// Замер 10.09.2026 на выборке из 707 опрашиваемых записей: при пяти
        /// нулях под удаление попадают 39% из них, и среди них живые —
        /// раздача rutor с одним сидом и склейка bitru+nnmclub с девятью.
        /// Публичный анонс их не видит: сиды сидят на анонсе самого трекера,
        /// а он посторонним не отвечает. При сорока нулях под удаление идут
        /// 1.8%, и живой опрос подтверждает у них ноль.
        ///
        /// Сорок проверок — это около трёх недель: круг по базе занимает
        /// примерно полсуток, и каждая раздача попадает под опрос раз за круг.
        /// </summary>
        public int deleteThreshold { get; set; } = 40;

        /// <summary>
        /// Удалять раздачи, набравшие <see cref="deleteThreshold"/> нулей.
        ///
        /// До 10.09.2026 стояло выключенным, и правильно: круг живости тогда
        /// не записывал подтверждённый ноль в саму раздачу, поэтому «достиг
        /// порога» не значило ничего.
        /// </summary>
        public bool deleteDead { get; set; } = false;
    }
}
