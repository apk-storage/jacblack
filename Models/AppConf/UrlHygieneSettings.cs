using System.Collections.Generic;

namespace JacRed.Models.AppConf
{
    /// <summary>
    /// Подмена мёртвых доменов в ссылках на раздачи — на выдаче, а не в базе.
    ///
    /// Домены трекеров меняются, а в записях остаётся тот, что был на момент
    /// обхода. Замер 29.07.2026: у kinozal **69% ссылок** вели на `kinozal.tv`,
    /// который вообще не резолвится — это около 160 тысяч записей, по которым
    /// человек из Лампы попадал в никуда.
    ///
    /// Правится здесь, а не переписыванием базы: изменение применяется ко всей
    /// базе сразу и не требует миграции на миллион с лишним записей. Список
    /// нарочно явный — подставлять «настроенный хост трекера» вслепую опасно,
    /// живое зеркало так можно сломать (`rutracker.net` жив и работает).
    /// </summary>
    public class UrlHygieneSettings
    {
        public bool enable { get; set; } = true;

        /// <summary>Мёртвый домен → живой. Сопоставление по всему имени хоста, регистр не важен.</summary>
        public Dictionary<string, string> replaceHosts { get; set; } = new Dictionary<string, string>
        {
            // Не резолвится с июня 2025, живое зеркало — kinozal.guru
            ["kinozal.tv"] = "kinozal.guru"
        };
    }
}
