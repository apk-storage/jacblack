namespace JacBlack.Models.AppConf
{
    /// <summary>
    /// Быстрый путь к хостам за проверкой Cloudflare: обычный HTTP-клиент,
    /// но с отпечатком TLS настоящего Chrome.
    ///
    /// Зачем. Браузер нужен ровно один раз — решить задачу и получить cookie
    /// `cf_clearance`. Дальше страницы отдаются обычному клиенту, если у него
    /// совпадает отпечаток TLS. Замер 07.09.2026 на rutracker: 0.13 с на
    /// страницу против 3.9 с через FlareSolverr — разница в тридцать раз.
    ///
    /// Ровно это уже проверяли 27.07.2026 и получили 403 — но проверяли
    /// клиентом .NET, у которого отпечаток свой, и clearance к нему не
    /// подходит. С отпечатком Chrome 124/131/136 та же cookie открывает и
    /// листинги (127 КБ), и поиск (250 КБ).
    ///
    /// Отпечаток берёт сторонний контейнер `cffetch` — в .NET подменить
    /// рукопожатие TLS нечем.
    /// </summary>
    public class CfFetchSettings
    {
        public bool enable { get; set; } = true;

        /// <summary>Адрес службы-помощника.</summary>
        public string url { get; set; } = "http://cffetch:8192/fetch";

        /// <summary>
        /// Какой Chrome изображаем. Должен быть НЕ старше того, в котором
        /// решалась задача: с `chrome116` та же cookie давала 403
        /// (`cf-mitigated: challenge`), потому что сессия браузера была 148-й.
        /// </summary>
        public string impersonate { get; set; } = "chrome131";

        /// <summary>
        /// Сколько ждать страницу в ПОИСКЕ — там ответа ждёт человек. Снижено
        /// с 25 до 10 секунд 14.09.2026: мёртвый выход для конкретного хоста
        /// уводил запрос в пустоту на все двадцать пять (так вело себя us1 для
        /// rutracker — 30 секунд молчания против 0,1–0,7 у остальных выходов).
        /// </summary>
        public int timeoutSeconds { get; set; } = 10;

        /// <summary>
        /// То же для ОБХОДА. У него цена ожидания другая: на часы никто не
        /// смотрит, зато оборванная страница теряется совсем, а разделы бывают
        /// тяжёлые. Поэтому прежние двадцать пять секунд остаются здесь.
        /// </summary>
        public int crawlTimeoutSeconds { get; set; } = 25;

        /// <summary>
        /// Сколько страниц берём одновременно. Ограничение своё, потому что
        /// у быстрого пути нет естественного тормоза браузера: без него обход
        /// упрётся в ограничение частоты самого трекера и получит 429.
        /// </summary>
        public int maxConcurrent { get; set; } = 4;

        /// <summary>
        /// Сколько минут доверять cookie без перепроверки. Дальше она не
        /// выбрасывается — просто первый же отказ уводит на браузер, и тот
        /// выдаёт свежую.
        /// </summary>
        public int clearanceMinutes { get; set; } = 60;
    }
}
