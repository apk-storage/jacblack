namespace JacBlack.Models.AppConf
{
    /// <summary>
    /// Доступ к TMDB — нужен ровно за одним: узнать год выхода СЕЗОНА.
    ///
    /// Зачем вообще. Год у раздачи разбирается из названия, а сценовые релизы
    /// его не пишут никогда: «The.Boys.S05E08.1080p.WEB.H264-SYLiX». Год в
    /// запросе при этом обязателен как условие отбора, поэтому такие раздачи
    /// выбывали целиком — у piratebay по «The Boys» так терялось 49 из 51.
    ///
    /// Подставить год премьеры сериала нельзя: карточка «The Boys» датирована
    /// 2019 годом, а пятый сезон вышел в 2026-м. Нужен год конкретного сезона,
    /// и это ровно то, что отдаёт TMDB одним запросом на карточку.
    ///
    /// Ключ здесь, а не в коде: он личный и в репозиторий попасть не должен.
    /// Пустой ключ — путь просто выключен, остальные способы добыть год
    /// (словари IMDB и Кинопоиска) работают по-прежнему.
    /// </summary>
    public class TmdbSettings
    {
        /// <summary>Ключ TMDB API v3. Пусто — обращений к TMDB нет вовсе.</summary>
        public string apiKey { get; set; } = null;

        /// <summary>
        /// Сколько ждать ответа TMDB, мс. Запрос идёт внутри поиска, поэтому
        /// срок короткий: не ответили — отдаём выдачу без сезонных лет, а не
        /// заставляем человека ждать. Промах кешируется отдельно, чтобы
        /// молчащий TMDB не тормозил каждый следующий поиск.
        /// </summary>
        public int timeoutMs { get; set; } = 2500;

        /// <summary>
        /// Сколько часов держать карту сезонов карточки. Даты сезонов меняются
        /// редко (разве что анонсированный сезон получит точную дату), поэтому
        /// сутки — с запасом.
        /// </summary>
        public int cacheHours { get; set; } = 24;

        /// <summary>
        /// Язык ответа. На даты не влияет, но пусть будет предсказуемым.
        /// </summary>
        public string language { get; set; } = "ru-RU";
    }
}
