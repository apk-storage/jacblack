namespace JacBlack.Models.AppConf
{
    /// <summary>
    /// Опрос трекеров о живых сидах в момент поиска.
    /// Появился потому, что сиды в базе — это снимок на момент индексации:
    /// 98.8% записей старше года, и проверка показала, что 73% из них мертвы.
    /// </summary>
    public class ScrapeSettings
    {
        public bool enable { get; set; } = true;

        /// <summary>
        /// Сколько всего миллисекунд разрешено потратить на опрос в рамках одного
        /// поиска. Лампа ждёт ответа, поэтому бюджет жёсткий: вышли за него —
        /// отдаём то, что успели, остальное берём из базы.
        /// </summary>
        public int budgetMs { get; set; } = 800;

        /// <summary>Таймаут одного обращения к трекеру.</summary>
        public int trackerTimeoutMs { get; set; } = 600;

        /// <summary>Сколько минут держать результат опроса в памяти.</summary>
        public int cacheMinutes { get; set; } = 15;

        /// <summary>
        /// Сколько минут помнить, что трекеры про раздачу НЕ ответили.
        /// Без этого мы спрашиваем о них снова при каждом поиске и каждый раз
        /// выжигаем весь бюджет: замер 29.07.2026 показал, что повторный поиск
        /// того же фильма занимал те же 900 мс при полном кеше ответов.
        /// Держим недолго — трекер мог просто моргнуть.
        /// </summary>
        public int noAnswerMinutes { get; set; } = 5;

        /// <summary>
        /// Максимум трекеров, опрашиваемых на один поиск. Раздачи группируются
        /// по трекерам, самые «населённые» опрашиваются первыми.
        /// </summary>
        /// <summary>
        /// Сколько трекеров опрашивать. Набор подбирается жадно — так, чтобы
        /// закрыть как можно больше раздач, а не просто взять самые частые.
        /// Было 4: раздачи, чей трекер в четвёрку не попадал, не опрашивались
        /// вовсе и показывали старое число из базы.
        /// </summary>
        public int maxTrackers { get; set; } = 10;

        /// <summary>
        /// Хешей в одном пакете. Протокол допускает до 74 — больше не влезает
        /// в типичный MTU и ответ обрежется.
        /// </summary>
        public int maxHashesPerRequest { get; set; } = 70;

        /// <summary>
        /// Раздачи, у которых опрос показал ноль сидов, опускать в конец выдачи.
        /// Не удаляем: ноль на трекере не всегда означает смерть — раздача может
        /// жить на DHT или на трекере, которого нет в ссылке.
        /// </summary>
        public bool demoteDead { get; set; } = true;

        /// <summary>
        /// Сколько миллисекунд догревать кеш в фоне, уже отдав ответ. 0 — не догревать.
        ///
        /// Зачем. Синхронный бюджет мал намеренно — 800 мс, иначе поиск станет
        /// медленным. Но при сотне результатов в него укладывается меньшинство,
        /// а остальным отдаётся значение из базы. Оно врёт: замер 31.07.2026 по
        /// сериалу «Извне» показал, что раздачи с «5», «4», «12» сидами на своих
        /// трекерах имеют ровно ноль. Люди это заметили.
        ///
        /// Догрев ничего не стоит посетителю: ответ уже ушёл. Зато следующий
        /// запрос по той же карточке — а Лампа спрашивает не по разу — берёт
        /// числа из кеша и показывает правду.
        /// </summary>
        public int backgroundFillMs { get; set; } = 20000;

        /// <summary>
        /// Сколько ВЕРХНИХ раздач (по заявленным сидам) проверять живьём за поиск.
        /// Бюджет мал, и раньше он размазывался по всей выдаче — из 439 результатов
        /// живо подтверждалось ~150 вразброс, а видимый верх оставался серым.
        /// Теперь бюджет тратится на то, что человек реально видит сверху: верх
        /// списка почти весь подтверждён, низ — значение из базы (догревается фоном).
        /// 0 — проверять все (старое поведение).
        /// </summary>
        public int topVerify { get; set; } = 60;
    }
}
