#!/usr/bin/env python3
"""Вернуть `Dalvik/` в список чужих — по решению Сергея 10.10.2026.

Днём я это правило снял, решив, что под него попадают телевизоры с
оригинальной Лампой. Сергей разобрал мой довод: «если я поставлю клиент
байлампы, запрос то от меня будет, а не от их сервера» — и он прав, адреса
людей ничего не доказывают.

Что доказано логом: APK оригинальной Лампы представляется `okhttp` и ходит в
`v1.0` с `search=` (1876 запросов, ноль с `Query=`), а все 105 запросов с
`Dalvik/` идут Jackett-путём `v2.0` с `Query=`. То есть это нативное чужое
приложение, а не нынешняя Лампа. Отличить от СТАРОЙ Лампы нечем, и на это
решение Сергея прямое: «да и в жопу её».
"""
import io
import sys

ПУТЬ = "/etc/nginx/nginx.conf"
ЯКОРЬ = '\t\t"~*Fishka-TV"                            1;\n'
НОВОЕ = ЯКОРЬ + '\t\t# Безымянный нативный Android-клиент. Оригинальная Лампа ходит\n' \
                '\t\t# `okhttp` в v1.0 с `search=`, а эти — Jackett-путём с `Query=`.\n' \
                '\t\t# Старые сборки Лампы уйдут вместе с ними: решение Сергея\n' \
                '\t\t# 10.10.2026 — «да и в жопу её».\n' \
                '\t\t"~*^Dalvik/"                             1;\n'

текст = io.open(ПУТЬ, encoding="utf-8").read()
if "Dalvik" in текст:
    sys.exit("Dalvik уже в списке")
if ЯКОРЬ not in текст:
    sys.exit("якорь Fishka-TV не найден — конфиг изменился, вслепую не правлю")

io.open(ПУТЬ, "w", encoding="utf-8", newline="\n").write(текст.replace(ЯКОРЬ, НОВОЕ, 1))
print("Dalvik возвращён в список чужих")
