#!/usr/bin/env python3
"""Правка nginx на awg: отсечь чужие сборки и приложения от поиска jac.black.

Решение Сергея 10.10.2026: «все лампак сборки — нахер», «должно работать
только с оригинальной ламой», «всякие призмы, вокино, байлампы, алкопаки и
прочее должны идти лесом». И тут же важная оговорка: «надо не отсечь ТВ с
виджетом Lampa и MSX», «а также iPad и ПК из браузера».

Белый список для этого НЕ ГОДИТСЯ, и это проверено на живом конфиге в тот же
день: список «клиент Лампы или браузер телевизора» отсёк настоящих клиентов —
приложение для ПК (`Lampa/1.5.10`), приложение для iOS (`Lampa/572
CFNetwork`), iPad, iPhone, Firefox и Chrome с компьютера. Правку откатили
через полчаса. Отличить браузер человека от сервера, который прикидывается
браузером, по User-Agent нельзя — значит перечисляем ЧУЖИХ, а не своих.

Кого отсекаем и почему (замер по суточному логу):

* `film.mov` (2 188) — чужое приложение, ходит через российский вход;
* `Chrome/106.0.0.0` РОВНО этой версии (118) — подпись сборок Lampac: по ней
  же их опознаёт и наш собственный код (`rqnum` в JackettSearchService);
* `TV-Gotovo-Parser-Gateway` (105) — чужой шлюз;
* `CheckHost` (31) — сканер;
* `Fishka-TV-Android` (15) — чужое приложение;
(Luxo из списка исключён 10.10.2026 по слову Сергея — приложению доступ оставлен.)
* `Dalvik/` (2) — голый Android-клиент: ни браузер, ни Лампа;
* ровно `Mozilla/5.0` без скобок (92) — браузером не бывает; шлёт
  `limit=12&sort=sid`, чего Лампа не шлёт.

Два адреса ловятся только по адресу, потому что присылают обычный браузерный
User-Agent без Origin, а объём выдаёт сервер:

* `46.205.193.233` (4 148 запросов, ERANET/blueconnect, Польша) — ровным
  темпом 10–16 в минуту весь день;
* `2a00:b700:5::22f` (92) — он же голый `Mozilla/5.0`.

Это тот же порядок, что приняли 15.09.2026 для перебиральщика каталога: по
классу адресов не режем, только конкретный адрес с доказанным объёмом.

Чужие ВЕБ-сборки (bylampa.online, siaivo, kinohub.uk, lampa.stream,
lampakan.ru, lampa.land) отсекать не нужно — их уже ловит заслон
`$svoi_origin`: Origin они присылают.
"""
import io
import sys

NGINX = "/etc/nginx/nginx.conf"
VHOST = "/etc/nginx/sites-enabled/jac.black"

ЯКОРЬ_MAP = '\tmap "$klient_biblioteka:$eto_poisk" $rezat_parser {'

БЛОК = '''	# ── Чужие сборки и приложения ─────────────────────────────────────────
	# Решение Сергея 10.10.2026: «все лампак сборки — нахер», «всякие
	# призмы, вокино, байлампы, алкопаки и прочее должны идти лесом».
	#
	# Перечисляем ЧУЖИХ, а не своих. Белый список в тот же день попробовали
	# и откатили: он отсёк приложения Лампы для ПК и iOS, iPad, iPhone,
	# Firefox и Chrome с компьютера. Браузер человека от сервера,
	# прикидывающегося браузером, по User-Agent не отличить.
	#
	# Сергей отдельно просил не задеть ТВ с виджетом Lampa и MSX — здесь они
	# и не упомянуты: MSX работает в браузере телевизора, а под чужих
	# подходит только явное имя приложения.
	map $http_user_agent $chuzhaya_sborka {
		default 0;
		# Подпись сборок Lampac — ровно эта версия Chrome. По ней же их
		# опознаёт наш код (`rqnum`).
		"~*Chrome/106\\.0\\.0\\.0"                 1;
		"~*film\\.mov"                            1;
		"~*TV-Gotovo-Parser-Gateway"             1;
		"~*Fishka-TV"                            1;
		"~*CheckHost"                            1;
		"~*^Dalvik/"                             1;
		# Ровно «Mozilla/5.0» и ничего больше: браузером не бывает.
		"~^Mozilla/5\\.0$"                        1;
	}

	map "$chuzhaya_sborka:$eto_poisk" $rezat_sborku {
		default 0;
		"1:1"   1;
	}

'''

ЯКОРЬ_GEO = "\t\t144.31.4.206 1;"

ВСТАВКА_GEO = """\t\t144.31.4.206 1;
\t\t# 46.205.193.233 — ERANET/blueconnect (Польша): 4 148 запросов за сутки
\t\t# ровным темпом 10–16 в минуту под видом Chrome на Linux, без Origin.
\t\t# 2a00:b700:5::22f — он же голый «Mozilla/5.0», шлёт limit=12&sort=sid.
\t\t# Оба отсечены 10.10.2026 по тому же правилу, что и перебиральщик выше:
\t\t# по классу адресов не режем, только конкретный с доказанным объёмом.
\t\t46.205.193.233 1;
\t\t2a00:b700:5::22f 1;"""

ЯКОРЬ_VHOST = """        if ($rezat_parser) {
            return 403;
        }
"""

ВСТАВКА_VHOST = """        if ($rezat_parser) {
            return 403;
        }

        # Чужая сборка или приложение — отказ. Список в $chuzhaya_sborka
        # (nginx.conf). Браузеры, iPad, ПК и ТВ с виджетом Лампы не задеты.
        if ($rezat_sborku) {
            return 403;
        }
"""


def правка(путь, якорь, замена, сколько=1):
    текст = io.open(путь, encoding="utf-8").read()
    есть = текст.count(якорь)
    if есть < сколько:
        sys.exit("якорь не найден в %s (нашлось %d из %d)"
                 % (путь, есть, сколько))
    io.open(путь, "w", encoding="utf-8", newline="\n").write(
        текст.replace(якорь, замена, сколько))


правка(NGINX, ЯКОРЬ_MAP, БЛОК + ЯКОРЬ_MAP)
правка(NGINX, ЯКОРЬ_GEO, ВСТАВКА_GEO)
правка(VHOST, ЯКОРЬ_VHOST, ВСТАВКА_VHOST, сколько=2)

print("правка внесена: $chuzhaya_sborka и два адреса в geo, заслон в двух location")
